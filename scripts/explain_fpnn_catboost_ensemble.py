"""
Reviewer-oriented interpretation of the 0.5 FPProcessNN + 0.5 CatBoost ensemble.

This script is intentionally aligned with 02_train_fp_catboost_cycle.py:

* property regressors use success == 1 rows when configured that way;
* FPProcessNN reads two 679-dimensional precursor fingerprints and a
  14-dimensional process vector;
* CatBoost uses the target-specific selected feature lists recorded in
  catboost_training_summary.csv;
* predictions are averaged across all saved seeds and then fused as
  0.5 * FPProcessNN + 0.5 * CatBoost;
* Stokes shift is derived as Em - Ex and is not trained as an independent
  target.

The analysis deliberately avoids the previous Zeroing/weighted-cosine method.
It produces:

1. Ensemble-level grouped permutation importance. Raw recipe fields are
   permuted and BOTH model representations are rebuilt before prediction.
2. Component performance for FPProcessNN, CatBoost, and their 0.5/0.5 ensemble.
3. Native CatBoost SHAP values, scaled by the CatBoost ensemble weight (0.5).
4. A proxy-feature diagnostic comparing simple size/composition/aromaticity
   features with the complete selected CatBoost feature set under repeated CV.
5. Bootstrap/replicate uncertainty, CSV tables, and manuscript-ready figures.

Important statistical note
--------------------------
For reviewer-grade performance claims, ``evaluation_file`` should be a genuinely
held-out experimental dataset that was not used to train the saved models.
If it is left blank, the script analyzes the expanded training data and labels
the resulting performance table as descriptive/in-sample. Feature associations
remain useful diagnostically, but in-sample metrics must not be presented as
generalization performance.

Run
---
1. Put this script beside the revised 02 training script.
2. Edit Config.run_dir and, if necessary, Config.training_script.
3. Optionally set Config.evaluation_file to an external test file.
4. Run:

       python explain_fpnn_catboost_ensemble.py

Dependencies
------------
numpy, pandas, scipy, scikit-learn, matplotlib, seaborn, torch, catboost,
rdkit, openpyxl, and the same local ``model.model`` module used for training.
"""

