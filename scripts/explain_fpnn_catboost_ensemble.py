def discover_nn_seeds(model_dir: Path) -> list[int]:
    seeds = []
    for p in model_dir.glob("FPProcessNN_seed*.pt"):
        m = re.search(r"seed(\d+)\.pt$", p.name)
        if m:
            seeds.append(int(m.group(1)))
    if not seeds:
        raise FileNotFoundError(f"No FPProcessNN_seed*.pt models in {model_dir}")
    return sorted(set(seeds))


def discover_cb_seeds(model_dir: Path, target: str) -> list[int]:
    seeds = []
    for p in model_dir.glob(f"catboost_{target}_seed*.cbm"):
        m = re.search(r"seed(\d+)\.cbm$", p.name)
        if m:
            seeds.append(int(m.group(1)))
    if not seeds:
        raise FileNotFoundError(
            f"No CatBoost models for {target}: {model_dir}/catboost_{target}_seed*.cbm"
        )
    return sorted(set(seeds))


def load_feature_lists(data_dir: Path) -> dict[str, list[str]]:
    summary_path = data_dir / "catboost_training_summary.csv"
    if not summary_path.exists():
        raise FileNotFoundError(
            f"Missing {summary_path}. Re-run the revised 02 training script."
        )
    summary = pd.read_csv(summary_path)
    if not {"target", "features"}.issubset(summary.columns):
        raise ValueError(
            "catboost_training_summary.csv must contain target and features columns."
        )
    result = {}
    for _, row in summary.iterrows():
        target = str(row["target"])
        features = [
            x.strip() for x in str(row["features"]).split(";")
            if x.strip() and x.strip().lower() != "nan"
        ]
        result[target] = list(dict.fromkeys(features))
    missing = [t for t in BASE_TARGETS if t not in result]
    if missing:
        raise ValueError(f"Missing CatBoost feature lists for: {missing}")
    return result


def load_eval_recipes(cfg: Config, paths: dict, tm) -> tuple[pd.DataFrame, str]:
    raw = read_table(paths["evaluation"])
    raw = tm.ensure_shift_and_success_columns(raw)
    processed = tm.data_process(raw).reset_index(drop=True)
    processed = tm.ensure_shift_and_success_columns(processed)

    required = [
        "precursor_1", "precursor_2", "reagent_1",
        "temperature", "time_h", "pre_1_mmol", "pre_2_mmol",
        *BASE_TARGETS,
    ]
    missing = [c for c in required if c not in processed.columns]
    if missing:
        raise ValueError(f"Evaluation data missing required columns: {missing}")

    processed = processed.dropna(subset=required).copy()
    if cfg.evaluate_success_only and "success" in processed.columns:
        mask = pd.to_numeric(processed["success"], errors="coerce") >= cfg.success_threshold
        processed = processed.loc[mask].reset_index(drop=True)
    if len(processed) < 10:
        raise ValueError(
            f"Only {len(processed)} usable evaluation rows remain; at least 10 are required."
        )

    is_external = paths["evaluation"] != paths["expanded"]
    scope = "external_test" if is_external else "descriptive_in_sample"
    return processed.reset_index(drop=True), scope


class SavedEnsemble:
    def __init__(self, cfg: Config, paths: dict, tm):
        self.cfg = cfg
        self.paths = paths
        self.tm = tm
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

        with (paths["model_dir"] / "y_scaler.pkl").open("rb") as f:
            self.y_scaler: StandardScaler = pickle.load(f)

        smiles_sheet = pd.read_excel(paths["smiles"])
        self.featurizer = tm.CarbonDotFeaturizer(
            smiles_sheet, tm.get_solvent_polarity_data()
        )

        smiles_compound = pd.read_excel(paths["smiles"], sheet_name="compound")
        self.compound_features, self.fp_objects = tm.build_compound_feature_table(
            smiles_compound
        )

        self.nn_seeds = discover_nn_seeds(paths["model_dir"])
        self.nn_models = []
        for seed in self.nn_seeds:
            model = tm.FPProcessNN().to(self.device)
            state = torch.load(
                paths["model_dir"] / f"FPProcessNN_seed{seed}.pt",
                map_location=self.device,
            )
            model.load_state_dict(state)
            model.eval()
            self.nn_models.append(model)

        self.feature_lists = load_feature_lists(paths["data_dir"])
        self.cb_seeds = {
            target: discover_cb_seeds(paths["model_dir"], target)
            for target in BASE_TARGETS
        }
        self.cb_models: dict[str, list[CatBoostRegressor]] = {}
        for target in BASE_TARGETS:
            models = []
            for seed in self.cb_seeds[target]:
                model = CatBoostRegressor()
                model.load_model(
                    str(paths["model_dir"] / f"catboost_{target}_seed{seed}.cbm")
                )
                models.append(model)
            self.cb_models[target] = models

    def build_cat_features(self, recipes: pd.DataFrame) -> pd.DataFrame:
        return self.tm.build_dataset_features(
            recipes.copy(), self.compound_features, self.fp_objects, has_targets=True
        )

    def predict_fpnn(self, recipes: pd.DataFrame) -> np.ndarray:
        dataset = self.tm.FPProcessDataset(
            recipes.reset_index(drop=True), self.featurizer, has_y=False
        )
        loader = DataLoader(
            dataset,
            batch_size=min(256, max(1, len(dataset))),
            shuffle=False,
            collate_fn=self.tm.collate_fn,
            num_workers=0,
        )
        seed_predictions = []
        for model in self.nn_models:
            batches = []
            with torch.no_grad():
                for batch in loader:
                    scaled = model(
                        batch["fps_1"].to(self.device),
                        batch["fps_2"].to(self.device),
                        batch["global_feat"].to(self.device),
                    ).cpu().numpy()
                    batches.append(self.y_scaler.inverse_transform(scaled))
            seed_predictions.append(np.vstack(batches))
        return np.mean(np.stack(seed_predictions, axis=0), axis=0)

    def predict_catboost(
        self, recipes: pd.DataFrame, feature_df: pd.DataFrame | None = None
    ) -> np.ndarray:
        if feature_df is None:
            feature_df = self.build_cat_features(recipes)
        columns = []
        for target in BASE_TARGETS:
            features = self.feature_lists[target]
            missing = [c for c in features if c not in feature_df.columns]
            if missing:
                raise ValueError(
                    f"Generated feature table lacks {target} features: {missing[:20]}"
                )
            x = feature_df[features].copy()
            for c in features:
                x[c] = pd.to_numeric(x[c], errors="coerce").fillna(0.0)
            preds = np.column_stack([
                model.predict(x) for model in self.cb_models[target]
            ])
            columns.append(preds.mean(axis=1))
        return np.column_stack(columns)

    def predict_all(self, recipes: pd.DataFrame) -> dict[str, np.ndarray]:
        feature_df = self.build_cat_features(recipes)
        fpnn = self.predict_fpnn(recipes)
        cat = self.predict_catboost(recipes, feature_df)
        ens = self.cfg.fpnn_weight * fpnn + self.cfg.catboost_weight * cat
        return {
            "FPNN": add_stokes(fpnn),
            "CatBoost": add_stokes(cat),
            "Ensemble": add_stokes(ens),
        }


def add_stokes(pred3: np.ndarray) -> np.ndarray:
    pred3 = np.asarray(pred3, dtype=float)
    shift = pred3[:, 1] - pred3[:, 0]
    return np.column_stack([pred3, shift])


def measured_matrix(df: pd.DataFrame) -> np.ndarray:
    y3 = df[BASE_TARGETS].astype(float).to_numpy()
    return add_stokes(y3)


def metric_row(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    component: str,
    scope: str,
) -> list[dict]:
    rows = []
    for j, target in enumerate(ALL_TARGETS):
        yt, yp = y_true[:, j], y_pred[:, j]
        rows.append({
            "component": component,
            "target": target,
            "n": len(yt),
            "r2": r2_score(yt, yp),
            "rmse": math.sqrt(mean_squared_error(yt, yp)),
            "mae": mean_absolute_error(yt, yp),
            "evaluation_scope": scope,
        })
    return rows


def paired_bootstrap_metrics(
    y_true: np.ndarray,
    predictions: dict[str, np.ndarray],
    cfg: Config,
    scope: str,
) -> pd.DataFrame:
    rng = np.random.default_rng(cfg.random_seed)
    n = len(y_true)
    alpha = (1.0 - cfg.confidence_level) / 2.0
    records = []
    for _ in range(cfg.bootstrap_repeats):
        idx = rng.integers(0, n, size=n)
        for component, pred in predictions.items():
            for j, target in enumerate(ALL_TARGETS):
                yt, yp = y_true[idx, j], pred[idx, j]
                records.append({
                    "component": component,
                    "target": target,
                    "r2": r2_score(yt, yp) if np.unique(yt).size > 1 else np.nan,
                    "rmse": math.sqrt(mean_squared_error(yt, yp)),
                    "mae": mean_absolute_error(yt, yp),
                })
    boot = pd.DataFrame(records)
    summary = (
        boot.groupby(["component", "target"])
        .agg(
            r2_boot_mean=("r2", "mean"),
            r2_ci_low=("r2", lambda s: s.quantile(alpha)),
            r2_ci_high=("r2", lambda s: s.quantile(1 - alpha)),
            rmse_boot_mean=("rmse", "mean"),
            rmse_ci_low=("rmse", lambda s: s.quantile(alpha)),
            rmse_ci_high=("rmse", lambda s: s.quantile(1 - alpha)),
            mae_boot_mean=("mae", "mean"),
            mae_ci_low=("mae", lambda s: s.quantile(alpha)),
            mae_ci_high=("mae", lambda s: s.quantile(1 - alpha)),
        )
        .reset_index()
    )
    summary["evaluation_scope"] = scope
    return summary


def existing_columns(df: pd.DataFrame, names: list[str]) -> list[str]:
    return [c for c in names if c in df.columns]


def raw_recipe_groups(df: pd.DataFrame) -> dict[str, list[str]]:
    groups = {
        # The pair is permuted jointly, preserving observed valid precursor pairs.
        "Precursor pair identity": ["precursor_1", "precursor_2"],
        "Precursor amounts": [
            "pre_1_mmol", "pre_2_mmol", "mass_1_g", "mass_2_g",
            "Mass1(g)", "Mass2(g)",
        ],
        "Solvent identity": ["reagent_1"],
        "Solvent volume": ["reagent_1_mL"],
        "Temperature": ["temperature"],
        "Reaction time": ["time_h"],
        "Joint process conditions": [
            "reagent_1", "reagent_1_mL", "temperature", "time_h",
            "pre_1_mmol", "pre_2_mmol", "mass_1_g", "mass_2_g",
            "Mass1(g)", "Mass2(g)",
        ],
        "Complete recipe": [
            "precursor_1", "precursor_2", "reagent_1", "reagent_1_mL",
            "temperature", "time_h", "pre_1_mmol", "pre_2_mmol",
            "mass_1_g", "mass_2_g", "Mass1(g)", "Mass2(g)",
        ],
    }
    clean = {}
    for name, cols in groups.items():
        cols = existing_columns(df, cols)
        if cols:
            clean[name] = list(dict.fromkeys(cols))
    return clean


def permute_group(
    df: pd.DataFrame, columns: list[str], rng: np.random.Generator
) -> pd.DataFrame:
    out = df.copy()
    order = rng.permutation(len(out))
    # One shared order preserves relationships within the selected group.
    out.loc[:, columns] = out.iloc[order][columns].to_numpy()
    return out


def grouped_permutation_importance(
    recipes: pd.DataFrame,
    y_true: np.ndarray,
    predictor: SavedEnsemble,
    baseline_predictions: dict[str, np.ndarray],
    cfg: Config,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    groups = raw_recipe_groups(recipes)
    rng = np.random.default_rng(cfg.random_seed + 101)
    raw_rows = []

    baseline = {}
    for component, pred in baseline_predictions.items():
        for j, target in enumerate(ALL_TARGETS):
            baseline[(component, target)] = {
                "r2": r2_score(y_true[:, j], pred[:, j]),
                "rmse": math.sqrt(mean_squared_error(y_true[:, j], pred[:, j])),
                "mae": mean_absolute_error(y_true[:, j], pred[:, j]),
            }

    for group, columns in groups.items():
        print(f"[Permutation] {group}: {columns}")
        for repeat in range(cfg.permutation_repeats):
            permuted = permute_group(recipes, columns, rng)
            predictions = predictor.predict_all(permuted)
            for component, pred in predictions.items():
                for j, target in enumerate(ALL_TARGETS):
                    r2 = r2_score(y_true[:, j], pred[:, j])
                    rmse = math.sqrt(mean_squared_error(y_true[:, j], pred[:, j]))
                    mae = mean_absolute_error(y_true[:, j], pred[:, j])
                    b = baseline[(component, target)]
                    raw_rows.append({
                        "group": group,
                        "columns": ";".join(columns),
                        "repeat": repeat + 1,
                        "component": component,
                        "target": target,
                        "baseline_r2": b["r2"],
                        "permuted_r2": r2,
                        "delta_r2": b["r2"] - r2,
                        "baseline_rmse": b["rmse"],
                        "permuted_rmse": rmse,
                        "delta_rmse": rmse - b["rmse"],
                        "baseline_mae": b["mae"],
                        "permuted_mae": mae,
                        "delta_mae": mae - b["mae"],
                    })

    raw = pd.DataFrame(raw_rows)
    alpha = (1.0 - cfg.confidence_level) / 2.0
    summary = (
        raw.groupby(["group", "columns", "component", "target"])
        .agg(
            n_repeats=("repeat", "count"),
            delta_r2_mean=("delta_r2", "mean"),
            delta_r2_sd=("delta_r2", "std"),
            delta_r2_ci_low=("delta_r2", lambda s: s.quantile(alpha)),
            delta_r2_ci_high=("delta_r2", lambda s: s.quantile(1 - alpha)),
            delta_rmse_mean=("delta_rmse", "mean"),
            delta_rmse_sd=("delta_rmse", "std"),
            delta_rmse_ci_low=("delta_rmse", lambda s: s.quantile(alpha)),
            delta_rmse_ci_high=("delta_rmse", lambda s: s.quantile(1 - alpha)),
            delta_mae_mean=("delta_mae", "mean"),
            delta_mae_sd=("delta_mae", "std"),
        )
        .reset_index()
    )
    return raw, summary


def feature_family(name: str) -> str:
    n = name.lower()
    if re.search(r"(^|_)fp_?\d+$", n) or "fingerprint" in n:
        return "Morgan fingerprint bits"
    if n.startswith(("p1_", "p2_")):
        return "Precursor molecular descriptors"
    if n.startswith(("pair_", "qy_pair_", "qy_temp_x_pair", "qy_time_x_pair")):
        return "Precursor-pair chemistry"
    if n.startswith("solv_") or any(
        token in n for token in [
            "dielectric", "pi_star", "hbd", "hba", "et30", "pka", "orp",
            "density", "specific_heat", "viscosity", "boiling",
        ]
    ):
        return "Solvent descriptors"
    if any(token in n for token in ["temperature", "time_h", "temp_time", "temp_over_time"]):
        return "Temperature/time"
    if any(token in n for token in ["mmol", "mass_", "reagent_to_precursor"]):
        return "Amounts/stoichiometry"
    if any(token in n for token in ["tanimoto", "intersection", "union", "xor"]):
        return "Pair fingerprint similarity"
    return "Other engineered features"


def catboost_shap(
    feature_df: pd.DataFrame,
    predictor: SavedEnsemble,
    cfg: Config,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    long_frames = []
    summaries = []

    for target in BASE_TARGETS:
        features = predictor.feature_lists[target]
        x = feature_df[features].copy()
        for c in features:
            x[c] = pd.to_numeric(x[c], errors="coerce").fillna(0.0)

        seed_shap = []
        for model in predictor.cb_models[target]:
            values = model.get_feature_importance(
                Pool(x), type="ShapValues"
            )[:, :-1]
            seed_shap.append(values)

        # First average explanations across CatBoost seeds; then multiply by
        # CatBoost's explicit 0.5 contribution to the final ensemble.
        shap_values = (
            np.mean(np.stack(seed_shap, axis=0), axis=0)
            * cfg.catboost_weight
        )
        long = pd.DataFrame(shap_values, columns=features)
        long.insert(0, "row_id", np.arange(len(long)))
        long = long.melt(
            id_vars="row_id", var_name="feature", value_name="weighted_shap"
        )
        long["feature_value"] = [
            x.iloc[int(row_id)][feature]
            for row_id, feature in zip(long["row_id"], long["feature"])
        ]
        long["target"] = target
        long["feature_family"] = long["feature"].map(feature_family)
        long_frames.append(long)

        s = pd.DataFrame({
            "target": target,
            "feature": features,
            "feature_family": [feature_family(f) for f in features],
            "mean_abs_weighted_shap": np.mean(np.abs(shap_values), axis=0),
            "mean_signed_weighted_shap": np.mean(shap_values, axis=0),
            "shap_sd_across_rows": np.std(shap_values, axis=0, ddof=1),
        }).sort_values("mean_abs_weighted_shap", ascending=False)
        s["rank"] = np.arange(1, len(s) + 1)
        summaries.append(s)

    return pd.concat(long_frames, ignore_index=True), pd.concat(summaries, ignore_index=True)


PROXY_PATTERNS = [
    "pair_sum_MolWt", "pair_sum_ExactMolWt", "pair_sum_HeavyAtomCount",
    "pair_sum_NumAromaticRings", "pair_sum_RingCount",
    "pair_sum_HeteroAtomCount", "pair_sum_NumAtoms",
    "pair_total_C", "pair_total_N", "pair_total_O", "pair_total_S",
    "pair_total_P", "pair_N_to_C", "pair_O_to_C", "pair_S_to_C",
    "pair_P_to_C", "pair_both_aromatic", "pair_one_aromatic_one_nonaromatic",
    "pair_sum_NumHAcceptors", "pair_sum_NumHDonors",
    "pair_sum_NumRotatableBonds", "pair_sum_FractionCSP3",
    "pair_sum_TPSA", "pair_sum_MolLogP",
]


def proxy_columns(feature_df: pd.DataFrame) -> list[str]:
    cols = [c for c in PROXY_PATTERNS if c in feature_df.columns]
    # Fall back to interpretable pair summaries if naming differs slightly.
    if len(cols) < 8:
        regex = re.compile(
            r"^pair_(sum_)?(MolWt|ExactMolWt|HeavyAtomCount|"
            r"NumAromaticRings|RingCount|HeteroAtomCount|NumAtoms|"
            r"[CNOSP]_count|total_[CNOSP]|[NOSP]_to_C|"
            r"NumHAcceptors|NumHDonors|TPSA|MolLogP|FractionCSP3)$"
        )
        cols.extend([c for c in feature_df.columns if regex.search(c)])
    return list(dict.fromkeys(cols))


def repeated_cv_proxy_diagnostic(
    feature_df: pd.DataFrame,
    predictor: SavedEnsemble,
    cfg: Config,
) -> pd.DataFrame:
    proxies = proxy_columns(feature_df)
    if len(proxies) < 3:
        raise ValueError(
            "Too few simple proxy descriptors were found. Check generated "
            "CatBoost feature names."
        )

    cv = RepeatedKFold(
        n_splits=cfg.cv_splits,
        n_repeats=cfg.cv_repeats,
        random_state=cfg.random_seed,
    )
    rows = []
    for target in BASE_TARGETS:
        y = feature_df[target].astype(float).to_numpy()
        full_cols = predictor.feature_lists[target]
        feature_sets = {
            "Simple proxy descriptors": proxies,
            "Selected CatBoost features": full_cols,
        }
        for fold, (train_idx, test_idx) in enumerate(cv.split(feature_df), start=1):
            for set_name, columns in feature_sets.items():
                x = feature_df[columns].copy()
                for c in columns:
                    x[c] = pd.to_numeric(x[c], errors="coerce").fillna(0.0)
                model = CatBoostRegressor(
                    loss_function="RMSE",
                    iterations=cfg.proxy_cb_iterations,
                    learning_rate=cfg.proxy_cb_learning_rate,
                    depth=cfg.proxy_cb_depth,
                    l2_leaf_reg=5.0,
                    random_seed=cfg.random_seed + fold,
                    verbose=False,
                    allow_writing_files=False,
                )
                model.fit(x.iloc[train_idx], y[train_idx], verbose=False)
                pred = model.predict(x.iloc[test_idx])
                rows.append({
                    "target": target,
                    "feature_set": set_name,
                    "fold": fold,
                    "n_features": len(columns),
                    "r2": r2_score(y[test_idx], pred),
                    "rmse": math.sqrt(mean_squared_error(y[test_idx], pred)),
                    "mae": mean_absolute_error(y[test_idx], pred),
                })
    return pd.DataFrame(rows)


def summarize_proxy_cv(raw: pd.DataFrame) -> pd.DataFrame:
    return (
        raw.groupby(["target", "feature_set", "n_features"])
        .agg(
            n_folds=("fold", "count"),
            r2_mean=("r2", "mean"),
            r2_sd=("r2", "std"),
            rmse_mean=("rmse", "mean"),
            rmse_sd=("rmse", "std"),
            mae_mean=("mae", "mean"),
            mae_sd=("mae", "std"),
        )
        .reset_index()
    )


def save_prediction_table(
    recipes: pd.DataFrame,
    y_true: np.ndarray,
    predictions: dict[str, np.ndarray],
    out: Path,
) -> None:
    keep = existing_columns(
        recipes,
        [
            "experiment_id", "cycle", "precursor_1", "precursor_2",
            "reagent_1", "pre_1_mmol", "pre_2_mmol",
            "temperature", "time_h", "success",
        ],
    )
    result = recipes[keep].reset_index(drop=True).copy()
    for j, target in enumerate(ALL_TARGETS):
        result[f"measured_{target}"] = y_true[:, j]
        for component, pred in predictions.items():
            result[f"{component}_{target}"] = pred[:, j]
    result.to_csv(out, index=False, encoding="utf-8-sig")


