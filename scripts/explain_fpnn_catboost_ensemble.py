def import_training_module(path: Path):
    spec = importlib.util.spec_from_file_location("fpnn_catboost_training_module", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot import training script: {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    required = [
        "FPProcessNN", "FPProcessDataset", "collate_fn",
        "build_compound_feature_table", "build_dataset_features",
        "CarbonDotFeaturizer", "get_solvent_polarity_data",
        "data_process", "ensure_shift_and_success_columns",
    ]
    missing = [name for name in required if not hasattr(module, name)]
    if missing:
        raise AttributeError(
            f"Training script is missing required definitions: {missing}"
        )
    return module


def load_json(path: Path) -> dict:
    if not path.exists():
        return {}
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


