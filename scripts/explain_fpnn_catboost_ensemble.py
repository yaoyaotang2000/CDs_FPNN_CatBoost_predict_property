def main(cfg: Config) -> None:
    set_seed(cfg.random_seed)
    if not np.isclose(cfg.fpnn_weight + cfg.catboost_weight, 1.0):
        raise ValueError("fpnn_weight + catboost_weight must equal 1.0")

    training_script = locate_training_script(cfg.training_script)
    tm = import_training_module(training_script)
    paths = resolve_paths(cfg)
    outdir = paths["output"]

    print(f"Training script: {training_script}")
    print(f"Run directory: {paths['run_dir']}")
    print(f"Evaluation file: {paths['evaluation']}")
    print(f"Output directory: {outdir}")

    recipes, scope = load_eval_recipes(cfg, paths, tm)
    y_true = measured_matrix(recipes)
    predictor = SavedEnsemble(cfg, paths, tm)

    print("\n[1/5] Baseline predictions and component metrics")
    predictions = predictor.predict_all(recipes)
    metrics = pd.DataFrame(
        sum(
            [
                metric_row(y_true, pred, component, scope)
                for component, pred in predictions.items()
            ],
            [],
        )
    )
    metrics.to_csv(outdir / "component_metrics.csv", index=False, encoding="utf-8-sig")

    metric_ci = paired_bootstrap_metrics(y_true, predictions, cfg, scope)
    metric_ci.to_csv(
        outdir / "component_metrics_bootstrap_ci.csv",
        index=False, encoding="utf-8-sig",
    )
    save_prediction_table(
        recipes, y_true, predictions, outdir / "evaluation_predictions.csv"
    )

    print("\n[2/5] Complete-ensemble grouped permutation importance")
    perm_raw, perm_summary = grouped_permutation_importance(
        recipes, y_true, predictor, predictions, cfg
    )
    perm_raw.to_csv(
        outdir / "grouped_permutation_importance_raw.csv",
        index=False, encoding="utf-8-sig",
    )
    perm_summary.to_csv(
        outdir / "grouped_permutation_importance_summary.csv",
        index=False, encoding="utf-8-sig",
    )

    print("\n[3/5] CatBoost native SHAP contribution")
    feature_df = predictor.build_cat_features(recipes)
    shap_long, shap_summary = catboost_shap(feature_df, predictor, cfg)
    shap_long.to_csv(
        outdir / "catboost_shap_values_long.csv",
        index=False, encoding="utf-8-sig",
    )
    shap_summary.to_csv(
        outdir / "catboost_shap_summary.csv",
        index=False, encoding="utf-8-sig",
    )

    print("\n[4/5] Simple-proxy diagnostic under repeated CV")
    proxy_raw = repeated_cv_proxy_diagnostic(feature_df, predictor, cfg)
    proxy_summary = summarize_proxy_cv(proxy_raw)
    proxy_raw.to_csv(
        outdir / "proxy_cv_raw.csv", index=False, encoding="utf-8-sig"
    )
    proxy_summary.to_csv(
        outdir / "proxy_cv_summary.csv", index=False, encoding="utf-8-sig"
    )

    print("\n[5/5] SCI figures and manifest")
    plot_main_figure(metrics, perm_summary, shap_summary, proxy_summary, cfg, outdir)
    plot_permutation_heatmap(perm_summary, cfg, outdir)

    manifest = {
        **asdict(cfg),
        "training_script": str(training_script),
        "resolved_paths": {
            k: str(v) for k, v in paths.items()
            if k != "train_config"
        },
        "evaluation_scope": scope,
        "n_evaluation_rows": len(recipes),
        "fpnn_seeds": predictor.nn_seeds,
        "catboost_seeds": predictor.cb_seeds,
        "catboost_feature_counts": {
            k: len(v) for k, v in predictor.feature_lists.items()
        },
        "targets": ALL_TARGETS,
        "interpretation_guardrail": (
            "Associative model interpretation only; not causal/mechanistic proof."
        ),
    }
    with (outdir / "interpretability_manifest.json").open(
        "w", encoding="utf-8"
    ) as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
    write_readme(cfg, paths, scope, len(recipes), outdir)

    print("\nAnalysis complete.")
    print(f"Results: {outdir}")
    print(f"Evaluation scope: {scope}")
    if scope != "external_test":
        print(
            "WARNING: metrics are descriptive/in-sample. Set evaluation_file "
            "to a genuinely unseen test set for generalization claims."
        )


